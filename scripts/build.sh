#!/usr/bin/env bash
# Builds the Scribes program. Run inside WSL from anywhere.
# The program keypair lives outside the repo; it is copied in for the build only.
set -euo pipefail
. "$HOME/.cargo/env"
export PATH="$HOME/.local/share/solana/install/active_release/bin:$PATH"
cd "$(dirname "$0")/.."
mkdir -p target/deploy
cp /mnt/c/Users/Admin/scribes-keys/program-scribes-2.json target/deploy/scribes-keypair.json
# Solana's platform tools bundle an older Cargo; resolve dependencies to versions it can build.
if [ ! -f Cargo.lock ]; then
  CARGO_RESOLVER_INCOMPATIBLE_RUST_VERSIONS=fallback cargo +stable generate-lockfile
  cargo +stable update -p blake3 --precise 1.5.5
fi
anchor build
# Keep the committed interface in step with the program (the type helper's generated header is replaced).
mkdir -p lib/idl
cp target/idl/scribes.json lib/idl/scribes.json
{ echo "// Type helper for the Scribes program interface (generated by anchor build; JSON in lib/idl/scribes.json)."; sed '1,/^ \*\//d' target/types/scribes.ts; } > lib/idl/scribes.ts
ls -l target/deploy/*.so target/idl/*.json
